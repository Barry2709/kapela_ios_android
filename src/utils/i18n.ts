export function getTranslation(key: keyof typeof translations.cs, params?: Record<string, string | number>, lang?: 'cs' | 'sk' | 'en'): string {
  const { language } = useAppStore.getState();
  const getSystemLanguage = (): 'cs' | 'sk' | 'en' => {
    try {
      const locale = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
      if (locale.startsWith('sk')) return 'sk';
      if (locale.startsWith('cs') || locale.startsWith('cz')) return 'cs';
      return 'en';
    } catch {
      return 'en';
    }
  };
  const currentLang = lang || (language === 'system' ? getSystemLanguage() : language);
  const langObj = (translations as any)[currentLang] || translations.en || translations.cs;
  let text = (langObj as any)?.[key] || (translations.cs as any)?.[key] || key;

  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }

  return text;
}

export function useTranslation() {
  const { language } = useAppStore();

  const getSystemLanguage = (): 'cs' | 'sk' | 'en' => {
    try {
      const locale = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
      if (locale.startsWith('sk')) return 'sk';
      if (locale.startsWith('cs') || locale.startsWith('cz')) return 'cs';
      return 'en';
    } catch {
      return 'en';
    }
  };

  const currentLang = language === 'system' ? getSystemLanguage() : language;

  const t = (key: keyof typeof translations.cs, params?: Record<string, string | number>): string => {
    return getTranslation(key, params, currentLang);
  };

  return { t, currentLang };
}
