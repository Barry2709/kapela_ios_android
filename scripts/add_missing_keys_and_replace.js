for (const lang of ['cs', 'sk', 'en']) {
  const langKeys = newKeys[lang];
  const langMatch = i18nContent.match(new RegExp(`(${lang}:\\s*\\{)`));
  if (langMatch) {
    let toInsert = '';
    const langBlockMatch = i18nContent.match(new RegExp(`${lang}:\\s*\\{([\\s\\S]*?)\\n  \\}`));
    for (const [key, val] of Object.entries(langKeys)) {
      if (langBlockMatch && !langBlockMatch[1].includes(`'${key}':`)) {
        toInsert += `\n    '${key}': '${val}',`;
      }
    }
    if (toInsert) {
      i18nContent = i18nContent.replace(langMatch[1], langMatch[1] + toInsert);
    }
  }
}

fs.writeFileSync(i18nPath, i18nContent);
console.log('Missing keys successfully added to i18n.ts');
