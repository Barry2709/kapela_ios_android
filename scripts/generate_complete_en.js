const missingInEn = [];
Object.keys(csEntries).forEach(k => {
  if (!enDictionary[k]) {
    missingInEn.push(k);
    enDictionary[k] = csEntries[k];
  }
});

console.log(`EN dictionary has ${Object.keys(enDictionary).length} keys. (Missing filled: ${missingInEn.length})`);

// Format en block as clean TS code
let enLines = '  en: {\n';
Object.entries(enDictionary).forEach(([k, v], idx, arr) => {
  const isLast = idx === arr.length - 1;
  const escapedVal = v.replace(/'/g, "\\'").replace(/\n/g, '\\n');
  enLines += `    '${k}': '${escapedVal}'${isLast ? '' : ','}\n`;
});
enLines += '  }';

// Rebuild i18n.ts content
const exportPos = content.indexOf('export function getTranslation');
const csCleanMatch = content.match(/cs:\s*\{([\s\S]*?)\},/);
const skCleanMatch = content.match(/sk:\s*\{[\s\S]*?\}(?=\s*\,|\s*\n\s*en:|\s*\n\s*\};)/);

if (csCleanMatch && skCleanMatch && exportPos !== -1) {
  const csText = csCleanMatch[0];
  const skText = skCleanMatch[0];

  const newTranslationsBlock = `const translations = {\n  ${csText}\n  ${skText},\n${enLines}\n};\n\n`;
  const headerText = content.substring(0, content.indexOf('const translations = {'));
  const footerText = content.substring(exportPos);

  const finalCode = headerText + newTranslationsBlock + footerText;
  fs.writeFileSync(i18nPath, finalCode);
  console.log('Successfully updated i18n.ts with complete EN translations!');
} else {
  console.error('Failed to parse blocks in i18n.ts');
}
